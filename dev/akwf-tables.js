// Builds dsp/include/nodal/akwf.h from resources/akwf: 80 single cycles of the Adventure Kid
// Waveforms (Kristoffer Ekstrand, CC0, github.com/KristofferKarlAxelEkstrand/AKWF-FREE),
// two per table. Each cycle becomes its harmonics (a direct DFT, 299 of them for a 600-sample
// cycle), RMS 1, so the plugin builds its tables without any computation at load time.
//   node dev/akwf-tables.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), dir = path.join(root, 'resources', 'akwf');
const picks = fs.readFileSync(path.join(dir, 'picks.txt'), 'utf8').trim().split(/\r?\n/).map(l => l.split(' '));

// Display names, by folder, in the order of picks.txt (each folder gives one table per pair).
const NAMES = {
  violin: ['Violin 1', 'Violin 2'], cello: ['Cello 1', 'Cello 2'], stringbox: ['String Box'],
  clarinett: ['Clarinet 1', 'Clarinet 2'], oboe: ['Oboe 1', 'Oboe 2'], flute: ['Flute 1', 'Flute 2'], altosax: ['Alto Sax 1', 'Alto Sax 2'],
  aguitar: ['Acoustic Gtr 1', 'Acoustic Gtr 2'], eguitar: ['Electric Gtr 1', 'Electric Gtr 2'],
  piano: ['Piano 1', 'Piano 2', 'Piano 3'], epiano: ['E-Piano 1', 'E-Piano 2'], clavinet: ['Clavinet'], eorgan: ['Organ 1', 'Organ 2'],
  dbass: ['Double Bass'], ebass: ['E-Bass'], hvoice: ['Voice 1', 'Voice 2', 'Voice 3'], theremin: ['Theremin'],
  fmsynth: ['FM 1', 'FM 2'], overtone: ['Overtone'], granular: ['Granular'], distorted: ['Distorted'], bitreduced: ['Bitreduced'],
  vgame: ['Video Game'], pluckalgo: ['Pluck'], sinharm: ['Harmonics'],
};

const readCycle = file => {
  const b = fs.readFileSync(file);
  if (b.toString('ascii', 0, 4) !== 'RIFF' || b.toString('ascii', 8, 12) !== 'WAVE') throw new Error(file + ': not a WAV');
  let at = 12, fmt = null, data = null;
  while (at + 8 <= b.length) {
    const id = b.toString('ascii', at, at + 4), size = b.readUInt32LE(at + 4);
    if (id === 'fmt ') fmt = { format: b.readUInt16LE(at + 8), channels: b.readUInt16LE(at + 10), bits: b.readUInt16LE(at + 22) };
    if (id === 'data') data = b.subarray(at + 8, at + 8 + size);
    at += 8 + size + (size & 1);
  }
  if (!fmt || !data || fmt.format !== 1 || fmt.bits !== 16) throw new Error(file + ': expected 16-bit PCM');
  const n = data.length / 2 / fmt.channels, x = new Float64Array(n);
  for (let i = 0; i < n; ++i) x[i] = data.readInt16LE(i * 2 * fmt.channels) / 32768;
  return x;
};
const harmonics = (x, count) => {
  const n = x.length, out = [];
  let energy = 0;
  for (let k = 1; k <= count; ++k) {
    let re = 0, im = 0;
    for (let i = 0; i < n; ++i) { const a = -2 * Math.PI * k * i / n; re += x[i] * Math.cos(a); im += x[i] * Math.sin(a); }
    re *= 2 / n; im *= 2 / n;
    out.push(re, im); energy += 0.5 * (re * re + im * im);
  }
  const g = energy > 1e-12 ? 1 / Math.sqrt(energy) : 0;
  return out.map(v => v * g);
};

const HARM = 299;  // a 600-sample cycle holds harmonics 1 .. 299
const byFolder = new Map();
for (const [folder, file] of picks) { if (!byFolder.has(folder)) byFolder.set(folder, []); byFolder.get(folder).push(file); }
const tables = [];
for (const [folder, files] of byFolder) {
  const names = NAMES[folder];
  if (!names || names.length * 2 !== files.length) throw new Error(folder + ': ' + files.length + ' files for ' + (names || []).length + ' tables');
  names.forEach((name, j) => {
    const a = files[2 * j], b = files[2 * j + 1];
    const ca = readCycle(path.join(dir, folder, a)), cb = readCycle(path.join(dir, folder, b));
    if (ca.length < 2 * HARM + 2 || cb.length < 2 * HARM + 2) throw new Error(folder + ': short cycle');
    tables.push({ name, a: a.replace(/\.wav$/, ''), b: b.replace(/\.wav$/, ''), data: [...harmonics(ca, HARM), ...harmonics(cb, HARM)] });
  });
}
const num = v => { const s = Math.abs(v) < 1e-6 ? '0' : v.toPrecision(5); return (s.includes('e') || s.includes('.') ? s : s + '.') + 'f'; };
let out = `#pragma once
// Generated by dev/akwf-tables.js from resources/akwf: do not edit.
// Adventure Kid Waveforms by Kristoffer Ekstrand, CC0 1.0 (public domain):
// https://github.com/KristofferKarlAxelEkstrand/AKWF-FREE
// ${tables.length} tables, each two single cycles (A, B): harmonics 1..${HARM} as (re, im), RMS 1.
namespace nodal::akwf {

constexpr int kHarm = ${HARM};
struct Table {
    const char* name;
    const char* a;  // the AKWF file of the first frame
    const char* b;  // and of the last
    const float* harm;  // 2 x kHarm x (re, im)
};

`;
tables.forEach((t, i) => {
  out += `inline const float kT${i}[] = {`;
  for (let j = 0; j < t.data.length; j += 12) out += '\n    ' + t.data.slice(j, j + 12).map(num).join(', ') + ',';
  out += '\n};\n';
});
out += `\ninline const Table kTables[] = {\n${tables.map((t, i) => `    {"${t.name}", "${t.a}", "${t.b}", kT${i}},`).join('\n')}\n};\nconstexpr int kCount = ${tables.length};\n\n}  // namespace nodal::akwf\n`;
fs.writeFileSync(path.join(root, 'dsp', 'include', 'nodal', 'akwf.h'), out);
console.log(`${tables.length} tables written: ${tables.map(t => t.name).join(', ')}`);
